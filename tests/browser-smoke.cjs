const { chromium } = require('playwright');
(async () => {
  const masterPassword = process.env.QUIZ_TEST_MASTER_PASSWORD || 'demo-master-password-2026';
  const browser = await chromium.launch({headless: true});
  const page = await browser.newPage();
  const failures = [];
  page.on('pageerror', e => failures.push(e.message));
  page.on('response', r => { if (r.status() >= 400 && new URL(r.url()).host === new URL(page.url()).host) failures.push(`${r.status()} ${r.url()}`); });
  await page.goto(process.env.QUIZ_URL || 'http://127.0.0.1:19091/', {waitUntil: 'networkidle'});
  await page.waitForFunction(() => { const text = document.querySelector("#root")?.innerText.trim() || ""; return text && !/^Loading\.?\.*$/i.test(text); }, null, {timeout: 20000});
  const initial = await page.request.get(new URL('/scalajsapi/getInitialData', page.url()).href);
  const initialData = Buffer.from(await initial.body()).map(b => b ^ 0xbd);
  if (initialData.includes(Buffer.from(masterPassword))) failures.push('Master secret leaked in initial data');
  const traversal = Buffer.from('../quiz-config.yml').toString('base64');
  const forbiddenAsset = await page.request.get(new URL('/quizassets/' + traversal + '.yml', page.url()).href);
  if (forbiddenAsset.status() !== 404) failures.push('Unlisted asset was accessible');
  const wrongLogin = await page.request.post(new URL('/master/login', page.url()).href, {headers: {'X-Requested-With': 'Quizmaster', 'Content-Type': 'text/plain'}, data:'wrong-password'});
  if (wrongLogin.status() !== 401) failures.push('Invalid master password was accepted');
  const content = await page.locator('#root').innerText();
  if (!content.trim()) failures.push('The application root is empty');
  await page.locator('input[type=text]').fill('CI test team');
  await page.getByRole('button', { name: 'Submit' }).click();
  await page.waitForURL('**/app/teamcontroller/**', {timeout: 10000});
  await page.getByText('CI test team', { exact: false }).first().waitFor();
  await page.goto(new URL('/app/', page.url()).href);
  page.once('dialog', dialog => dialog.accept(masterPassword));
  await page.locator('#master-secret-prompt-link').click();
  await page.waitForURL('**/app/quiz*', {timeout: 10000});
  await page.waitForTimeout(1000);
  const controlRequest = page.waitForRequest(r => r.url().includes('/doTeamOrQuizStateUpdate'), {timeout:5000});
  const controlResponse = page.waitForResponse(r => r.url().includes('/doTeamOrQuizStateUpdate'), {timeout:5000});
  await page.keyboard.press('ArrowRight');
  const sent = await controlRequest;
  if ((await controlResponse).status() !== 200) failures.push('Signed-in master control failed');
  const anonymous = await browser.newContext();
  const replay = await anonymous.request.post(sent.url(), {data:sent.postDataBuffer(),headers:{'Content-Type':'application/octet-stream','X-Requested-With':'Quizmaster'}});
  if (replay.status() !== 403) failures.push('Master control accepted without authentication');
  await anonymous.close();
  if (failures.length) throw new Error(failures.join('\n'));
  console.log('Application rendered:', content.slice(0, 160).replace(/\s+/g, ' '));
  await browser.close();
})().catch(e => { console.error(e); process.exit(1); });
